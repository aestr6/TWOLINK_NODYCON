tlac::cvmit = "Failed to converge within 100 iterations; starting from `1` the final error was `2`.";

tlac::lstol = "The step size is really small, `1`.";

tlac[Y_, opts:OptionsPattern[]] := Module[{Z, root, droot, eig, NS, h, hscale, step},
h = Y[[-1]];
NS = Y[[-2]];
(*Z = Y\[LeftDoubleBracket]1\[RightDoubleBracket] +h NS;*)

{hscale, Z} = teststep[h, Y[[1]], NS];
Do[
If[hscale <  2, Break[]];
h = h / 2;
{hscale, Z} = teststep[h, Y[[1]], NS],
{100}
];

If[Abs[h] < 10^-10, Message[tlac::lstol, h]; Throw[$Failed]];


Do[
{root, droot, eig} =  f[Z, opts];
AppendTo[root, NS . (Z-Y[[1]]) -  h];
AppendTo[droot, NS];
Check[step =  Inverse[droot] . root, Throw[Inverse::"luc"]];
If[Norm[step] < rtol || Norm[root] < atol, Break[];];
If[Norm[step] > 10, Throw[$Failed];];
Z = Z - step,
{100}];

If[Norm[root] > ftol, Message[tlac::cvmit, Y[[1]], Norm@root]; Throw[$Failed]];

NS = NullSpace[droot[[1;;-2, All]]];
h = If[NS[[1]] . Y[[-2]] < 0, -h, h];
{Z, Norm[root], eig,NS[[1]], h/hscale}
]


(* ::Input::Initialization:: *)
tle::cvmit = "Failed to converge within 100 iterations; starting from `1` the final error was `2`.";

tle[Y_, opts:OptionsPattern[]] := Module[{Z, root, droot, eig, step},
Z = Y;
Z[[1]] = Append[Y[[1, ;;-2]], Y[[1, -1]] + Y[[-1]]];
Do[
{root, droot, eig} =  f[Z[[1]], opts];
Check[step =  Inverse[droot] . root, Throw[Inverse::"luc"]];
If[Norm[step] < rtol || Norm[root] < atol, Break[];];
If[Norm[step] > 10, Throw[$Failed];];
Z[[1, ;;-2]] = Z[[1, ;;-2]] - step,
{100}];

If[Norm[root] > ftol, Message[tle::cvmit, Y[[1]], Norm@root]; Throw[$Failed]];

Z[[2]] = Norm[root];
Z[[3]] = eig;
Z
]


