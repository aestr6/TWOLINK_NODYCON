(* ::Input::Initialization:: *)
(* set up environment to compute derivatives *)
n = TwoLink`CompiledFunctions`n; 
(* dx(t)/dx0 = 4, dx(t)/dt = 1, and dx(t)/du = 1 *)
(* the derivative will have the first 4 columns be dx(t)/dx0 *)
\[Tau] =  {0,0,0,0,1,0}&; (* 5th column is dx(t)/dt *)
\[Mu] = {0,0,0,0,0,1}&; (* last column is dx(t)/du *)

(* initial condition: dx(0)/dx0 = I, dx(0)/dt = dx(0)/du = 0 *)
\[Xi]0 = IdentityMatrix[{4, n}];
x\[Xi]0 = Join[{0,0,0,0}, \[Xi]0] // Flatten;

(* global variables in this package *)
f = root1;
(* stopping criterions for Newton's method *)
rtol = 10^-8; (* stop if step size is really small *)
atol = 10^-8;(* stop if root is really good *)
ftol = 10^-5;(* reject if root is really bad *)


(* ::Input::Initialization:: *)
Options[tlmap] = Options[\[CurlyPhi]];
tlmap[x0_, u_, t_, opts:OptionsPattern[]] := Module[{x\[Xi], \[Tau]f},
(* initial condition for x(0) and \[Xi](0) *)
x\[Xi]0[[1;;4]] = x0;
(* solve for x(t), dx(t)/dx0, dx(t)/dt, and dx(t)/du *)
\[Tau]f = If[OptionValue[EventHandler], dtd\[Lambda], \[Tau]];
(* \[CurlyPhi] has same options as NDSolve *)
x\[Xi] = \[CurlyPhi][x\[Xi]0, (u)&, {0, t}, \[Mu],\[Tau]f, opts];

(* now impact *)
x\[Xi] = H[x\[Xi]];
(* extract final state and derivatives *)
{x\[Xi][[1;;4]], Partition[x\[Xi][[5;;-1]], n]}
]


(* ::Input::Initialization:: *)
(* implicit function setter *)
tlroot[fcn_]:= 
If[StringQ[fcn],
Which[
fcn == "pt", f = root1,
fcn == "pe", f = root2,
fcn == "at", f = root3,
fcn == "ae", f = root4],
f = fcn
];

(* implicit function for time-based passive brachiation *)
root1[\[Lambda]_, opts:OptionsPattern[]]:= Module[{x0, t, M, root, droot},
x0 = \[Lambda][[1;;4]]; 
t = \[Lambda][[5]];
M = tlmap[x0, 0, t, opts];
root = FixState[M[[1]] - x0];
droot = M[[2]] - \[Xi]0;
(* for passive we only want dxdx0 and dxdt *)
(* also return eigenvalues, since it'll be useful later *)
{root, droot[[All, 1;;5]], Eigenvalues[M[[2, All, 1;;4]]]}
]

(* implicit function for event-based passive brachiation *)
Options[root2] = {"t"-> 15} ~Join~ Options[\[CurlyPhi]];
root2[\[Lambda]_, opts:OptionsPattern[]]:= Module[{x0, M, root, droot},
x0 = \[Lambda];
M = tlmap[x0, 0, OptionValue["t"], FilterRules[{EventHandler-> True, opts}, Options[\[CurlyPhi]]]];
root = FixState[M[[1]] - x0];
droot = M[[2]] - \[Xi]0;
(* for passive we only want dxdx0 and dxdt *)
(* also return eigenvalues, since it'll be useful later *)
{root[[2;;4]], droot[[2;;4, 1;;4]], Eigenvalues[M[[2, All, 1;;4]]]}
]

(* implicit function for time-based powered brachiation *)
root3[\[Lambda]_, opts:OptionsPattern[]]:= Module[{x0, t, u, M, root, droot},
x0 = \[Lambda][[1;;4]]; 
t = \[Lambda][[5]];
u = \[Lambda][[6]];
M = tlmap[x0, u, t, opts];
root = FixState[M[[1]] - x0];
droot = M[[2]] - \[Xi]0;
(* for passive we only want dxdx0 and dxdt *)
(* also return eigenvalues, since it'll be useful later *)
{root, droot, Eigenvalues[M[[2, All, 1;;4]]]}
]

(* implicit function for event-based powered brachiation *)
Options[root4] = {"t"-> 15} ~Join~ Options[\[CurlyPhi]];
root4[\[Lambda]_, opts:OptionsPattern[]]:= Module[{x0, u, M, root, droot},
x0 = \[Lambda][[1;;4]];
u =  \[Lambda][[5]];
M = tlmap[x0, u, OptionValue["t"], FilterRules[{EventHandler-> True, opts}, Options[\[CurlyPhi]]]];
root = FixState[M[[1]] - x0];
droot = M[[2]] - \[Xi]0;
(* for passive we only want dxdx0 and dxdt *)
(* also return eigenvalues, since it'll be useful later *)
{root[[2;;4]], droot[[2;;4, {1,2,3,4,6}]], Eigenvalues[M[[2, All, 1;;4]]]}
]


(* ::Input::Initialization:: *)
nstol0 = 10^(-8);


(* ::Input::Initialization:: *)
tlc0::root = "\[Lambda] must yield a known root of f.  Norm[f(\[Lambda])] is too large `1` (> 10^-5).";

tlc0::bifurcation = "Bifurcation at `1`.  Selecting first tangent.";

tlc0[\[Lambda]0_, h_, opts:OptionsPattern[]] := Module[{root, droot, NS, eig},
(* set up initial point on our curve *)
{root, droot, eig} = f[\[Lambda]0, opts];
If[Norm[root] >  ftol, Message[tlc0::root,Norm[root]];Throw[$Failed]];
NS = NullSpace[droot, Tolerance->nstol0];
If[Length[NS] > 1, Message[tlc0::bifurcation,\[Lambda]0]];
If[Length[NS] > 0, {\[Lambda]0, Norm[root], eig,NS[[1]], h}, {\[Lambda]0, Norm[root], eig,h}
]
]


(* ::Input::Initialization:: *)
tlc::cvmit = "Failed to converge within 100 iterations; starting from `1` the final error was `2`.";

tlc[Y_, opts:OptionsPattern[]] := Module[{Z, root, droot, eig, NS, h, step},
h = Y[[-1]];
NS = Y[[-2]];
Z = Y[[1]] +h NS;

Do[
{root, droot, eig} =  f[Z, opts];
AppendTo[root, NS . (Z-Y[[1]]) -  h];
AppendTo[droot, NS];
Check[step =  PseudoInverse[droot] . root, Throw[Inverse::"luc"]];
If[Norm[step] < rtol || Norm[root] < atol, Break[];];
If[Norm[step] > 10, Throw[$Failed];];
Z = Z - step,
{100}];

If[Norm[root] > ftol, Message[tlc::cvmit, Y[[1]], Norm@root]; Throw[$Failed]];

NS = NullSpace[droot[[1;;-2, All]]];
h = If[NS[[1]] . Y[[-2]] < 0, -h, h];
{Z, Norm[root], eig,NS[[1]], h}
]


(* ::Input::Initialization:: *)
Options[teststep] = {"ders"-> {0.6, 0.05, 0.01}}
teststep[h_, Y_, NS_, opts:OptionsPattern[]] := Module[{g, dg, Z, step, ns, H, k, d, a, eig, kder, dder, ader},
(* Based on Numerical Continuation Methods, Allgower. *)
{kder, dder, ader} = OptionValue["ders"];
g = dg = step = ns = {0, 0};
Z = Y +h NS;

Do[
{g[[i]], dg[[i]], eig} =  f[Z, opts];
ns[[i]] = NullSpace[dg[[i]]];

AppendTo[g[[i]], NS . (Z-Y) - h];
AppendTo[dg[[i]], NS];

Check[step[[i]] =  Inverse[dg[[i]]] . g[[i]], Throw[Inverse::"luc"]];
Z = Z - step[[i]],
{i, 2}
];

H = Inverse[dg[[1]]];
k = Norm[H . g[[2]]] / Norm[H . g[[1]]];
d = Norm[step[[1]]];
a = Abs[ArcCos[ns[[1]] . ns[[2]]\[Transpose]]];

g = Max[Sqrt[k/kder], Sqrt[d/dder], a/ader];
g = Max[Min[g, 2], 1/2];

(*Print[ " k ",k,  " d ",d,  " a ",(a)[[1,1]], " g ", g];*)

{g, Z}
]


