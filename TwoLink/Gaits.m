tlcurve::info = "`1` took `2` s to run and has `3` points.";
tlcurve[name_, c_, \[Lambda]_, h_, m_, opts:OptionsPattern[]] := Module[{Z0, Z, time, n},
n = 0;
Z0 = tlc0[\[Lambda], h, opts];

Z = ConstantArray[0, {m+1, Length[Z0]}];
Z[[1]] = Z0;

time = AbsoluteTiming[Catch[Do[Z[[i+1]] = c[Z[[i]], opts]; n = i+1, {i, m}]]];
Message[tlcurve::info, name, time[[1]], n];

Z =Z[[;;n]]; (* truncate list to actual number of points *)
If[ h< 0, Reverse[Z], Z] (* flip, if negative direction *)
]


(* ::Input::Initialization:: *)
tlparcurve[name_, c_, \[Lambda]_, h_, m_, opts:OptionsPattern[]] := Module[{l, a, b, c0, c1, cs, o},
c0 = tlc0[\[Lambda], h, opts];
c1 =tlc[c0, opts];
a = 2h;
b = {{c0[[1]], Ceiling[m/2]}, {c1[[1]], Floor[m/2]-1}};
o = {opts};
DistributeDefinitions[name, c, a, b, o];
cs = ParallelTable[tlcurve[name, c, b[[i, 1]], a, b[[i, 2]], o], {i, 2}];
l = Min[Length@cs[[1]], Length@cs[[2]]];
Riffle[cs[[1, ;;l]], cs[[2, ;;l]]]
]

tlparcurve[args_, opts:OptionsPattern[]] := Module[{o},
o = {opts};
DistributeDefinitions[o];
ParallelTable[
tlroot[a[[1]]];
tlcurve[Sequence@@a[[2;;]], o], 
{a, args},
Method -> "FinestGrained"
]
]


