Begin["`CompiledFunctions`"]
Needs["DifferentialEquations`InterpolatingFunctionAnatomy`"];

n = 6; (* |\[Lambda]| for \[Lambda] = (x0, t, u) *)
SetAttributes[n,{Protected,Locked}]; (* \[CurlyPhi] isn't 100% general so lock n for now *)

timpact; (* records the impact time, changes with every call to \[CurlyPhi] *)

cf; (* an associative array of compiled functions *)
x\[Xi]0flow; (* initial condition used in shortened version of Flow *)
zfun; (* the zero function used in shortened version of Flow *)

(* update variables for shortened version of Flow *)
x\[Xi]0flow = ConstantArray[0, 4 (n+1)];
zfun = Evaluate[ConstantArray[0, n]]&;


CompileFunctions[] := 
Module[{var, vars, eqns, x0, \[Xi]0, x, u, t, \[Xi], \[Mu], \[Tau], F, DF, Ft, H, DH, Hinv, opts},
var[1] = Array[(x[#])&, 4];
var[2] = Array[(\[Xi][##])&, {4, n}];
var[3] = Array[(\[Mu][#])&, n];
var[4] = Array[(\[Tau][#])&, n];
var[5] = Array[(x0[#])&, 4];
var[6] = Array[(\[Xi]0[##])&, {4, n}];

F = TwoLink`Dynamics`F;
DF = TwoLink`Dynamics`DF;
Ft = TwoLink`Dynamics`Ft;
H = TwoLink`Dynamics`H;
DH = TwoLink`Dynamics`DH;
Hinv = TwoLink`Dynamics`Hinv;

(* store and then change defaults for Compile *)
opts = Options[Compile, {CompilationTarget, Parallelization}];
SetOptions[Compile, CompilationTarget-> "C", Parallelization-> True];

(* Compile derivatives for x(t) and \[Xi](t)=\[PartialD]x(t)/\[PartialD]\[Lambda] *)
vars = Join[var[1],Flatten[var[2]], {u}, var[3]];
eqns = Join[F[var[1], u], Flatten[DF[var[1], u, var[2], var[3]]]];
cf[1] = Compile[Evaluate[vars], Evaluate[eqns]];

vars = Join[var[1], Flatten[var[2]], {u}, var[4]];
eqns = Join[0 var[1], Flatten[Ft[var[1], u, var[4]]]];
cf[2] = Compile[Evaluate[vars], Evaluate[eqns]];

vars = Join[var[1], Flatten[var[2]]];
eqns = Chop[Join[H[var[1]], Flatten[DH[var[1]].var[2]]]];
cf[3] = Compile[Evaluate[vars], Evaluate[eqns]];

vars = Join[var[1], Flatten[var[2]]];
eqns = Join[Hinv[var[1]], Flatten[Inverse[DH[var[1]]].var[2]]];
cf[4] = Compile[Evaluate[vars], Evaluate[eqns]];

(* Compiled maps and energy functions *)
vars = Join[var[1], Flatten[var[2]]];
eqns =  TwoLink`Dynamics`Slope[var[1]];
cf[10] = Compile[Evaluate[vars], Evaluate[eqns]];

vars = Join[var[1], Flatten[var[2]], var[5], Flatten[var[6]]];
eqns =  TwoLink`Dynamics`S[var[1], var[5]];
cf[11] = Compile[Evaluate[vars], Evaluate[eqns]];
