(* helper functions for computing solutions *)
F[{x\[Xi]__}, u_, {\[Mu]__}]:= cf[1][x\[Xi],u, \[Mu]];
Ft[{x\[Xi]__}, u_, {\[Tau]__}]:= cf[2][x\[Xi], u, \[Tau]];
H[{x\[Xi]__}]:= cf[3][x\[Xi]];
Hinv[{x\[Xi]__}]:= cf[4][x\[Xi]];

Slope[{x\[Xi]__}] := cf[10][x\[Xi]];
S[{x\[Xi]__}, {x\[Xi]0__}] := cf[11][x\[Xi], x\[Xi]0];
DS[{x\[Xi]__}, {x\[Xi]0__}] := cf[12][x\[Xi], x\[Xi]0];
Energy[{x\[Xi]__}] := cf[13][x\[Xi]];
FixAngles[q_] := cf[14][q];
dtd\[Lambda][s_, {x\[Xi]__}, {x\[Xi]0__}] := cf[15][x\[Xi], x\[Xi]0];
ValidCrossing[{x\[Xi]__}, {x\[Xi]0__}] := cf[16][x\[Xi], x\[Xi]0];


(* solves the combined system d/dt {x (t), \[Xi] (t)} = {F, DF} *)
Options[\[CurlyPhi]] = {All-> False, Scale-> 1, EventHandler->False} ~Join~ Options[NDSolve];
\[CurlyPhi]::section = "The trajectory starting at `1` may not have crossed the section.";

\[CurlyPhi][x0_, u_, t_, opts:OptionsPattern[]] :=  (x\[Xi]0flow[[1;;4]] = x0;
\[CurlyPhi][x\[Xi]0flow, u, t, zfun, zfun, opts]);

\[CurlyPhi][x\[Xi]0_, u_, t_, \[Mu]_, \[Tau]_, opts:OptionsPattern[]] := 
Module[{s, t0, tf, T, dom, eqns, x, x\[Xi], e, a, ndopts},
a = OptionValue[All];
e = OptionValue[EventHandler];
T = OptionValue[Scale];

{t0, tf} = t/T;
dom= If[a || e, {s, t0, tf}, {s, tf, tf}];

eqns =  {
x\[Xi][t0] == x\[Xi]0,
x\[Xi]'[s] == T F[x\[Xi][s], u[s, x\[Xi][s]],\[Mu][s, x\[Xi][s]]]
};

ndopts = FilterRules[{opts}, Options[NDSolve]];
If[e, AppendTo[ndopts, 
Method->{"EventLocator", "Event"->  S[x\[Xi][s], x\[Xi]0],
"EventAction":> If[ValidCrossing[FixState[x\[Xi][s]], FixState[x\[Xi]0]], Throw[Null, "StopIntegration"]]}]];

s = NDSolve[eqns, x\[Xi], dom, ndopts];
If[!ListQ[s] || s == {}, Throw[$Failed]];
x\[Xi] = x\[Xi] /. First[s];

tf = InterpolatingFunctionDomain[x\[Xi]][[1,2]];
timpact = tf;
If[e && tf == t[[2]]/T, Message[\[CurlyPhi]::section, x\[Xi]0[[1;;4]]]];

If[a,Interpolation[Table[x = x\[Xi][s]; {{s}, x + Ft[x, u[s, x], \[Tau][s, x, x\[Xi]0]]}, {s, x\[Xi]["Coordinates"][[1]]}]],
x\[Xi] = x\[Xi][tf];
x\[Xi] + Ft[x\[Xi], u[tf, x\[Xi]], \[Tau][tf, x\[Xi], x\[Xi]0]]
]
];

timp[] := timpact;


End[]
