SetAttributes[FixSlopeAngles, Listable];
FixSlopeAngles[q_] := Module[{x}, 
(* make sure angles are btw (-pi/2 pi/2] *)
x = Mod[q, \[Pi]];
If[x>\[Pi]/2, x - \[Pi], x]
];

FixParameters[x_, q_:True, \[Sigma]_:True] := Module[{y = x}, 
If[ListQ[y[[1]]],
If[q, y[[All, 1;;2]] = FixAngles[y[[All, 1;;2]]];];
If[\[Sigma], y[[All, 6]] = FixSlopeAngles[y[[All, 6]]];];, 
(* else *)
If[q, y[[1;;2]] = FixAngles[y[[1;;2]]];];
If[\[Sigma], y[[6]] = FixSlopeAngles[y[[6]]];];
];
y
];


