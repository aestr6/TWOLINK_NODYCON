bif::mag = "Eigenvalue `` at `` does not have a magnitude near 1, |e| = ``.";

bif[c_, tb_:"tb"] := Module[{i, e, a},
i = Which[tb === "tb", 1, tb === "sb", 2, True, All];
e = SortBy[c[[3, i]], Max@Abs@#&][[3;;4]];
If[StringContainsQ[tb, "s"],
(* we always have an eigenvalue of +1 with state-based switching *)
(* choose the larger of the two if the smaller is +1 *)
e = If[PossibleZeroQ[Im@e[[1]]] && Re@e[[1]] > 0, e[[2]], e[[1]]];,
(* else *)
e = e[[2]];
];

If[Abs@e < 0.95, Message[bif::mag, e, c[[1]], Abs@e]];

{If[PossibleZeroQ[Im@e],  If[Re@e > 0, "FD", "PD"], "NS"], c[[1]]}
];


