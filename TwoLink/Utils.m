(* these variables & functions are not exported *)
Pmax = TwoLink`Dynamics`Energy[{\[Pi],0,0,0}];

Q[x2_] := Module[{m, p}, 
p = Inverse[TwoLink`Dynamics`P[{Infinity, x2}]];
m = TwoLink`Dynamics`M[{Infinity, x2}];
m - p\[Transpose] . m . p
];

Eloss[x0_] := 1/2 x0[[3;;4]] . Q[x0[[2]]] . x0[[3;;4]] - TwoLink`Dynamics`g(TwoLink`Dynamics`b+1)(Cos[x0[[1]]] + Cos[x0[[1]] + x0[[2]]]);

Egained[x0_] := -2{ub[x0] x0[[2]], uw[x0] x0[[2]] };

(*uw[x0_] := TwoLink`Utils`Eloss[x0]/(2(Mod[x0\[LeftDoubleBracket]2\[RightDoubleBracket], 2\[Pi]] - \[Pi]));*)
(*
FixAngles assumes only one pass through the circle.
ub[x0_] := TwoLink`Utils`Eloss[x0]/(2TwoLink`Dynamics`FixAngles[x0\[LeftDoubleBracket]2\[RightDoubleBracket]]);
uw[x0_] := TwoLink`Utils`Eloss[x0]/(2TwoLink`Dynamics`FixAngles[x0\[LeftDoubleBracket]2\[RightDoubleBracket]-\[Pi]]);*)

ub[x0_] := TwoLink`Utils`Eloss[x0]/(2x0[[2]]);
uw[x0_] := TwoLink`Utils`Eloss[x0]/(2(x0[[2]]-\[Pi]));

dEloss[{x1_, x2_, x3_, x4_, ___}] := Evaluate[D[TwoLink`Utils`Eloss[{x1, x2, x3, x4}], {{x1, x2, x3, x4}}]];

muw[x0_] := Join[dEloss[x0]/(2(x0[[2]]-\[Pi])) - TwoLink`Utils`Eloss[x0](2(x0[[2]]-\[Pi]))^-2(2x0[[2]]), {0,0}]

mub[x0_] := Join[dEloss[x0]/(2x0[[2]]) - TwoLink`Utils`Eloss[x0](2x0[[2]])^-2(2x0[[2]]), {0,0}]

x1[z1_, z3_] := Module[{m, n},
(* only yields x1 = [0, Pi] *)
m = ArcCos[z3/(TwoLink`Dynamics`g(TwoLink`Dynamics`b+1)) + 1];
n = \[Pi];
((n-m)Cos[z1] + m + n)/2 
];

x2[x1_, z3_] := {-ArcCos[z3/(TwoLink`Dynamics`g(TwoLink`Dynamics`b+1)) - Cos[x1]] - x1, ArcCos[z3/(TwoLink`Dynamics`g(TwoLink`Dynamics`b+1)) - Cos[x1]] - x1};

x3[x2_, z2_, z3_] := Module[{Q1, Q2, Q3}, 
(* note, we use round-off error to avoid div by 0 @ x2 = 0 & Pi *)
{Q1, Q2, Q3} = Flatten[Q[x2]][[{1,2,4}]];
Sqrt[Abs[-2 Q3 z3/(Q2^2 - Q1 Q3)]]Cos[z2]
];

x4[x2_,x3_, z3_] := Module[{x, q, d}, 
(* note Det returns 0 at x2 = 0 w/o round-off error.  Det is symmetric at Pi/2, so we take advantage of this to get correct values at x2 = 0 and Pi *)
x = Mod[x2, \[Pi]];
x = If[x > \[Pi]/2, \[Pi] - x, x];
q = Q[x2];
d = -Det[Q[x]];

{(-q[[1,2]] x3 - Sqrt[d x3^2 + 2 q[[2,2]] z3])/q[[2,2]],
(-q[[1,2]] x3 + Sqrt[d x3^2 + 2 q[[2,2]] z3])/q[[2,2]]}
];

x0[z1_, z2_, z3_, i2_:2, i4_:2] := Module[{q1, q2, dq1}, 
q1 = x1[z1, z3];
q2 = x2[q1, z3][[i2]];
dq1 = x3[q2, z2, z3];
{q1,  q2, dq1, x4[q2, dq1, z3][[i4]]}
];

xt[x0_] := TwoLink`Dynamics`Hinv[x0];


