PartitionCurve[curve_, tb_:"tb", tol_:10.0^-8] := Module[{p, i},
(* find all points that are asymptotically stable *)
i = Which[tb === "tb", 1, tb === "sb", 2, True, All];
p = With[{j = i}, Max@Abs@curve[[#, 3, j]] < 1+tol&];
i = SplitBy[Range@Length@curve, p];
i = {#, curve[[#]]}& /@ i;
Join[<|"u" -> {}, "s" -> {}|>, GroupBy[i, If[p[#[[1,1]]], "s", "u"]&]]
];


