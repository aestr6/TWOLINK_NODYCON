GaitBelowSlope[x0_] := Module[{\[Sigma], ss},
\[Sigma] = FixAngles@TwoLink`Dynamics`Slope[x0];
(* these angle would correspond to gaits beneath the slope *)
If[\[Sigma] > \[Pi]/2 || \[Sigma] <= -\[Pi]/2, \[Sigma] = \[Sigma] - Sign[\[Sigma]]\[Pi]];
(* test whether x0 is on the same side as a configuration with \[Nu] = 0 and \[Sigma] *)
ss = {Sin[-\[Sigma]], -Cos[-\[Sigma]]} . {Sin[x0[[1]]], -Cos[x0[[1]]]};
ss >= 0
];


